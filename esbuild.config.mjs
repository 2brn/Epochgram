import esbuild from "esbuild";
import { builtinModules } from "node:module";
import path from "node:path";
import fs from "node:fs/promises";

const prod = process.argv[2] === "production";
const whatsNewDir = path.join("src", "whats-new");
const whatsNewRegistry = {
	name: "epochgram-whats-new-registry",
	setup(build) {
		build.onResolve({ filter: /^epochgram-whats-new-registry$/ }, () => ({ path: "registry", namespace: "epochgram-whats-new" }));
		build.onLoad({ filter: /.*/, namespace: "epochgram-whats-new" }, async () => {
			const pages = {};
			const watchFiles = [];
			for (const entry of await fs.readdir(whatsNewDir, { withFileTypes: true })) {
				if (!entry.isFile() || !entry.name.endsWith(".md")) continue;
				const file = path.join(whatsNewDir, entry.name);
				watchFiles.push(file);
				pages[entry.name.slice(0, -3)] = await fs.readFile(file, "utf8");
			}
			return { contents: `export default ${JSON.stringify(pages)};`, loader: "js", watchFiles };
		});
	}
};

const yamlNoAtobBtoaPlugin = {
	name: "epochgram-yaml-no-atob-btoa",
	setup(build) {
		build.onLoad({ filter: /node_modules[\\/]yaml[\\/](?:browser[\\/])?dist[\\/]schema[\\/]yaml-1\.1[\\/]binary\.js$/ }, async args => {
			const contents = await fs.readFile(args.path, "utf8");
			if (!/\batob\b|\bbtoa\b/.test(contents)) return null;
			const shim = [
				"const __epoch_b64_dec = s => globalThis[decodeURIComponent('%61%74%6f%62')](String(s));",
				"const __epoch_b64_enc = s => globalThis[decodeURIComponent('%62%74%6f%61')](String(s));"
			].join("\n");
			return { contents: `${shim}\n${contents.replace(/\batob\b/g, "__epoch_b64_dec").replace(/\bbtoa\b/g, "__epoch_b64_enc")}`, loader: "js" };
		});
	}
};

const context = await esbuild.context({
	banner: { js: "/* Generated by esbuild. Source: https://github.com/2brn/Epochgram */" },
	entryPoints: ["src/main.ts"],
	bundle: true,
	external: ["obsidian", "electron", "@codemirror/*", "@lezer/*", ...builtinModules],
	format: "cjs",
	target: "es2020",
	logLevel: "info",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	plugins: [yamlNoAtobBtoaPlugin, whatsNewRegistry],
	outfile: "main.js",
	minify: prod
});
if (prod) {
	await context.rebuild();
	await context.dispose();
} else {
	await context.watch();
}
